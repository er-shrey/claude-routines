const { contextBridge, ipcRenderer } = require('electron');

const invoke = (channel) => (...args) => ipcRenderer.invoke(channel, ...args);

contextBridge.exposeInMainWorld('api', {
  getConfig: invoke('config:get'),
  saveConfig: invoke('config:save'),
  probeShell: invoke('config:probe'),
  setSecret: invoke('secrets:set'),
  removeSecret: invoke('secrets:remove'),
  importEnvFile: invoke('secrets:importEnvFile'),
  saveMcp: invoke('mcp:save'),
  removeMcp: invoke('mcp:remove'),
  importMcpJson: invoke('mcp:importJson'),
  testMcp: invoke('mcp:test'),
  claudeStatus: invoke('claude:status'),
  claudeMcpList: invoke('claude:mcpList'),
  reinstallSchedules: invoke('app:reinstallSchedules'),
  listRoutines: invoke('routines:list'),
  getRoutine: invoke('routines:get'),
  saveRoutine: invoke('routines:save'),
  setEnabled: invoke('routines:setEnabled'),
  deleteRoutine: invoke('routines:delete'),
  runNow: invoke('routines:runNow'),
  allowAndRerun: invoke('routines:allowAndRerun'),
  listRuns: invoke('runs:list'),
  getRun: invoke('runs:get'),
  stopRun: invoke('runs:stop'),
  listApprovals: invoke('approvals:list'),
  decide: invoke('approvals:decide'),
  pickMarkdown: invoke('dialog:pickMarkdown'),
  pickFolder: invoke('dialog:pickFolder'),
  pickJson: invoke('dialog:pickJson'),
  openPath: invoke('shell:open'),
  openLog: invoke('shell:openLog'),
  getHelp: invoke('help:get'),
  onApprovals: (cb) => ipcRenderer.on('approvals:changed', (_e, list) => cb(list)),
  onNav: (cb) => ipcRenderer.on('nav', (_e, nav) => cb(nav)),
});
